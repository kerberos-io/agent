#!/bin/sh
set -eu

root=/runtime
mkdir -p "$root/usr/bin" "$root/usr/sbin" "$root/usr/lib" "$root/etc" \
	"$root/var/lib/dpkg" "$root/dev/pts" "$root/proc" "$root/sys" "$root/run"
ln -s usr/bin "$root/bin"
ln -s usr/sbin "$root/sbin"
ln -s usr/lib "$root/lib"
if [ -L /lib64 ]; then
	mkdir -p "$root/usr/lib64"
	ln -s usr/lib64 "$root/lib64"
fi

# Package dependencies include dlopen-loaded codecs/drivers and their data, which
# ldd alone cannot discover. Debian resolves the native architecture's loader too.
apt-cache depends --recurse --installed --no-recommends --no-suggests \
	--no-conflicts --no-breaks --no-replaces --no-enhances \
	curl ffmpeg libatomic1 libstdc++6 dash coreutils findutils grep sed tzdata ncurses-base \
	> /tmp/runtime-dependencies
sed -n '/^[a-z0-9][a-z0-9+.:_-]*$/p' /tmp/runtime-dependencies \
	| grep -vx debconf | sort -u > /tmp/runtime-candidates
dpkg-query -W -f='${Package} ${db:Status-Status}\n' > /tmp/package-status
awk '$2 == "installed" { print $1 }' /tmp/package-status \
	| sort -u > /tmp/installed-packages
comm -12 /tmp/runtime-candidates /tmp/installed-packages > /tmp/runtime-packages

# The package list is generated from trusted package metadata, not build input.
packages=$(cat /tmp/runtime-packages)
dpkg-query -L $packages > /tmp/runtime-package-paths
sort -u /tmp/runtime-package-paths > /tmp/runtime-paths
while IFS= read -r path; do
	case "$path" in
		"") continue ;;
		/usr/share/doc/*/copyright|/usr/share/common-licenses/*) ;;
		/usr/share/doc/*|/usr/share/man/*|/usr/share/info/*|/usr/share/locale/*|\
		/usr/share/lintian/*|/usr/share/bug/*|/usr/share/debconf/*|\
		/usr/share/bash-completion/*|/usr/share/fish/*|\
		/usr/lib/systemd/*|/lib/systemd/*|/etc/init.d/*|/etc/cron.*/*) continue ;;
	esac
	if [ -d "$path" ] && [ ! -L "$path" ]; then
		continue
	fi
	if [ ! -f "$path" ] && [ ! -L "$path" ]; then
		printf 'Missing selected runtime file: %s\n' "$path" >&2
		exit 1
	fi
	printf '%s\n' "$path"
done < /tmp/runtime-paths > /tmp/runtime-files
tar --create --file /tmp/runtime.tar --no-recursion --files-from /tmp/runtime-files
tar --extract --file /tmp/runtime.tar --directory "$root"

# Preserve generated trust stores, font configuration/caches and pixbuf loaders.
cp -a --parents /etc/ssl /usr/lib/ssl /usr/share/ca-certificates /etc/fonts \
	/var/cache/fontconfig /usr/share/mime /usr/share/common-licenses "$root"
find /usr/lib -path '*/gdk-pixbuf-2.0/*/loaders.cache' \
	-exec cp -a --parents {} "$root" \;
cp -a --parents /etc/nsswitch.conf /etc/gai.conf /etc/localtime \
	/etc/ld.so.conf /etc/ld.so.conf.d /etc/os-release /etc/debian_version \
	/usr/lib/os-release /usr/lib/locale "$root"

# Some public SONAME links (BLAS/LAPACK, for example) are generated by Debian
# alternatives rather than owned by a package. Keep only links to selected files.
find /usr/lib -type l > /tmp/runtime-links
if [ -d /usr/lib64 ]; then
	find /usr/lib64 -type l >> /tmp/runtime-links
fi
while IFS= read -r link; do
	target=$(readlink -f "$link")
	if [ -e "$root$target" ]; then
		while [ -L "$link" ]; do
			cp -a --parents "$link" "$root"
			target=$(readlink "$link")
			case "$target" in
				/*) link=$target ;;
				*) link=$(dirname "$link")/$target ;;
			esac
		done
	fi
done < /tmp/runtime-links

getent passwd root agent nobody > "$root/etc/passwd"
getent group root kerberosio video nogroup > "$root/etc/group"
mkdir -p "$root/tmp" "$root/var/tmp"
chmod 1777 "$root/tmp" "$root/var/tmp"
install -d -m 0700 -o 999 -g 999 "$root/tmp/agent-cache"

# Retain package provenance for scanners without shipping apt/dpkg executables.
dpkg-query -s $packages ca-certificates base-files > "$root/var/lib/dpkg/status"
mkdir -p "$root/usr/share/doc/ca-certificates"
cp /usr/share/doc/ca-certificates/copyright "$root/usr/share/doc/ca-certificates/"
ldconfig -r "$root"
chroot "$root" /usr/bin/fc-cache --force
find "$root" -type f -perm /6000 -exec chmod a-s {} +
setcap 'cap_net_bind_service=+ep' "$root/home/agent/main"
getcap "$root/home/agent/main"

# Execute against the assembled loader/libraries, not the assembly-stage rootfs.
chroot --userspec=999:999 "$root" /bin/sh -ec '
	/home/agent/main -action version
	ffmpeg -version
	ffprobe -version
	curl --version
	test -s /etc/ssl/certs/ca-certificates.crt
	test ! -e /usr/bin/apt
	test ! -e /usr/bin/dpkg
'
